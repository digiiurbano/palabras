class I18nManager {
  constructor() {
    this.supportedLanguages = ['es', 'de', 'en'];
    this.currentLang = this.detectInitialLanguage();
  }

  detectInitialLanguage() {
    try {
      const stored = localStorage.getItem('jnp_lang');
      if (stored && this.supportedLanguages.includes(stored)) {
        return stored;
      }
      const browser = (navigator.language || navigator.userLanguage || '').slice(0, 2).toLowerCase();
      if (this.supportedLanguages.includes(browser)) {
        return browser;
      }
    } catch (e) {}
    return 'es'; // Predeterminado
  }

  t(key, lang = null) {
    const l = lang || this.currentLang || 'es';
    const dict = I18N_TRANSLATIONS[l] || I18N_TRANSLATIONS['es'];
    return dict[key] || I18N_TRANSLATIONS['es'][key] || key;
  }

  setLanguage(lang, silent = false) {
    if (!this.supportedLanguages.includes(lang)) return;
    this.currentLang = lang;
    try {
      localStorage.setItem('jnp_lang', lang);
    } catch (e) {}

    document.documentElement.lang = lang;
    this.applyTranslationsToDOM();
    this.updateLanguageSwitchers();

    if (!silent && typeof showToast === 'function') {
      showToast('🌍 Language / Idioma', this.t('lang_changed'), 'info', 2500);
    }

    // Disparar evento personalizado para componentes dinámicos
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  applyTranslationsToDOM() {
    // Textos directos
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) {
        el.innerHTML = val;
      }
    });

    // Placeholders
    const inputs = document.querySelectorAll('[data-i18n-placeholder]');
    inputs.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val) {
        el.setAttribute('placeholder', val);
      }
    });
  }

  updateLanguageSwitchers() {
    const buttons = document.querySelectorAll('.lang-btn');
    buttons.forEach(btn => {
      const lang = btn.getAttribute('data-lang');
      if (lang === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
  }

  renderLanguageSwitcherHTML(extraClass = '') {
    return `
      <div class="lang-switcher ${extraClass}" role="group" aria-label="Selector de idioma">
        <button type="button" class="lang-btn ${this.currentLang==='es'?'active':''}" data-lang="es" onclick="i18n.setLanguage('es')" title="Español">
          <span class="lang-flag">🇪🇸</span> <span class="lang-code">ES</span>
        </button>
        <button type="button" class="lang-btn ${this.currentLang==='de'?'active':''}" data-lang="de" onclick="i18n.setLanguage('de')" title="Deutsch">
          <span class="lang-flag">🇩🇪</span> <span class="lang-code">DE</span>
        </button>
        <button type="button" class="lang-btn ${this.currentLang==='en'?'active':''}" data-lang="en" onclick="i18n.setLanguage('en')" title="English">
          <span class="lang-flag">🇬🇧</span> <span class="lang-code">EN</span>
        </button>
      </div>
    `;
  }
}

// Inicializar instancia global
const i18n = new I18nManager();
window.i18n = i18n;

// Aplicar al cargar la página
document.addEventListener('DOMContentLoaded', () => {
  i18n.applyTranslationsToDOM();
  i18n.updateLanguageSwitchers();
});
